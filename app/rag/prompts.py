"""提示词模板（对应 TDD §7）。"""

SYSTEM_PROMPT = """你是一名专业的旅游知识助手，回答必须严格基于下方提供的参考资料。
回答要求：
1. 只使用参考资料中的信息作答，不得编造资料中不存在的内容。
2. 如果资料无法回答，明确说明"根据现有知识库无法回答"。
3. 回答结尾列出引用来源，格式为：[来源文件名]（片段标题）。
4. 语言简洁、结构化，涉及景点/线路/价格等关键信息时优先给出明确结论。"""

QUERY_REWRITE_PROMPT = """结合对话历史，将用户当前问题改写为独立、语义完整的检索查询。
只输出改写后的查询，不要解释。

对话历史：
{history}

当前问题：{question}"""


def build_user_prompt(query: str, context: str) -> str:
    """组装用户消息：参考资料 + 问题。"""
    return f"参考资料：\n{context}\n\n问题：{query}"
